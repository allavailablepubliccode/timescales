% make_parameter_space_figure.m
%
% Two-panel figure for the model's magnitude prediction.
%
%   Panel A: predicted intact/scrambled variance ratio as a function of
%            tau_max^scr at the reference spectral exponent, overlaid with
%            the empirical geometric-mean ratio, its bootstrap 95% CI, and
%            the 24 subject-wise ratios (shown as a marginal strip, since
%            individual ratios are measurements of the ratio only and carry
%            no tau_max^scr value of their own).
%
%   Panel B: predicted ratio across the full (tau_max^scr, alpha) parameter
%            space, with contours at the empirical point estimate and CI.
%
% Scientific parameter values are unchanged from v2. The reference point is
% at alpha = 0 exactly; it is labelled "Reference prediction" rather than
% "Literature point" because not every coordinate is literature-derived.
%
% Saves to the repository figures/ directory in PNG, PDF and SVG formats.

clear; clc; close all;

rng(42);   % fixed seed so the jitter in Panel A is reproducible

% -------------------------------------------------------------------------
% Fixed model parameters
% -------------------------------------------------------------------------
tau_min        = 0.05;       % s
tau_max_intact = 45.0;       % s
omega_min      = 2*pi/128;   % rad/s (0.0078 Hz)
omega_max      = 2*pi*0.1;   % rad/s (0.1 Hz)

% Reference point used for the headline model prediction
tau_scram_prior = 7.5;       % s
alpha_prior     = 0.0;

% Empirical result reported in the manuscript
emp_ratio = 1.21;
emp_ci    = [1.09 1.34];

% Subject-wise intact/scrambled PC1 variance ratios (Table 1)
subj_ratios = [0.83 1.84 1.35 1.44 0.87 1.37 1.35 0.70 0.87 1.47 0.98 0.81 ...
               1.13 1.31 1.19 1.20 1.14 1.35 1.55 1.66 1.36 1.46 1.67 1.09];

% -------------------------------------------------------------------------
% Joint parameter grid (Panel B)
% -------------------------------------------------------------------------
alpha_vals     = 0:0.05:2.0;
tau_scram_vals = 3.0:0.1:12.0;

ratio_surface = zeros(length(alpha_vals), length(tau_scram_vals));

% Numerical integration resolution
n_u = 20000;

fprintf('Computing model predictions across parameter space...\n');

for ia = 1:length(alpha_vals)
    alpha = alpha_vals(ia);

    G_intact = compute_G(tau_min, tau_max_intact, ...
        omega_min, omega_max, n_u, alpha);

    for it = 1:length(tau_scram_vals)
        G_scram = compute_G(tau_min, tau_scram_vals(it), ...
            omega_min, omega_max, n_u, alpha);

        ratio_surface(ia,it) = G_intact / G_scram;
    end
end

% -------------------------------------------------------------------------
% One-dimensional slice at the reference alpha (Panel A)
% -------------------------------------------------------------------------
n_u_fine       = 100000;
tau_slice_vals = 3.0:0.05:12.0;
ratio_slice    = zeros(size(tau_slice_vals));

G_intact_prior = compute_G(tau_min, tau_max_intact, ...
    omega_min, omega_max, n_u_fine, alpha_prior);

for it = 1:length(tau_slice_vals)
    G_scram = compute_G(tau_min, tau_slice_vals(it), ...
        omega_min, omega_max, n_u_fine, alpha_prior);

    ratio_slice(it) = G_intact_prior / G_scram;
end

% Headline prediction at the reference point
G_scram_prior = compute_G(tau_min, tau_scram_prior, ...
    omega_min, omega_max, n_u_fine, alpha_prior);

pred_prior = G_intact_prior / G_scram_prior;

fprintf('Predicted ratio at alpha = %.2f, tau_max_scram = %.1f s: %.4f\n', ...
    alpha_prior, tau_scram_prior, pred_prior);

fprintf('Empirical geometric mean ratio: %.2f (95%% CI %.2f-%.2f)\n', ...
    emp_ratio, emp_ci(1), emp_ci(2));

% -------------------------------------------------------------------------
% Figure
% -------------------------------------------------------------------------
fig = figure('Color','w','Position',[100 100 1500 640]);

y_lo = min([subj_ratios(:); ratio_slice(:); emp_ci(1)]) - 0.10;
y_hi = max([subj_ratios(:); ratio_slice(:); emp_ci(2)]) + 0.10;

% =========================== PANEL A =====================================
axA = axes('Position',[0.055 0.130 0.325 0.760]);
hold(axA,'on');

set(axA, ...
    'FontSize',12, ...
    'LineWidth',1, ...
    'Box','on');

% Empirical bootstrap 95% CI as a shaded band
h_bandA = fill(axA, ...
    [tau_slice_vals(1) tau_slice_vals(end) ...
     tau_slice_vals(end) tau_slice_vals(1)], ...
    [emp_ci(1) emp_ci(1) emp_ci(2) emp_ci(2)], ...
    [0.84 0.87 0.94], ...
    'EdgeColor','none');

% Empirical geometric mean ratio
h_meanA = plot(axA, ...
    [tau_slice_vals(1) tau_slice_vals(end)], ...
    [emp_ratio emp_ratio], ...
    '-', ...
    'Color',[0 0 0], ...
    'LineWidth',2.0);

% Model prediction as a function of tau_max^scr at alpha = 0
h_curveA = plot(axA, ...
    tau_slice_vals, ...
    ratio_slice, ...
    '-', ...
    'Color',[0.10 0.35 0.75], ...
    'LineWidth',2.6);

% Guide line at reference tau_max^scr
plot(axA, ...
    [tau_scram_prior tau_scram_prior], ...
    [y_lo pred_prior], ...
    ':', ...
    'Color',[0.35 0.35 0.35], ...
    'LineWidth',1.2, ...
    'HandleVisibility','off');

% Reference prediction
h_refA = plot(axA, ...
    tau_scram_prior, ...
    pred_prior, ...
    'o', ...
    'MarkerSize',11, ...
    'MarkerFaceColor',[0.10 0.35 0.75], ...
    'MarkerEdgeColor','k', ...
    'LineWidth',1.6);

xlim(axA,[tau_slice_vals(1) tau_slice_vals(end)]);
ylim(axA,[y_lo y_hi]);

xlabel(axA, ...
    'Maximum scrambled-condition timescale, \tau_{max}^{scr} (s)');

ylabel(axA, ...
    'Intact/scrambled variance ratio');

title(axA, ...
    sprintf('A   Magnitude prediction (\\alpha = %.1f)',alpha_prior), ...
    'FontWeight','bold', ...
    'HorizontalAlignment','left', ...
    'Units','normalized', ...
    'Position',[0 1.02]);

lgdA = legend(axA, ...
    [h_curveA h_meanA h_bandA h_refA], ...
    {'Model prediction', ...
     sprintf('Empirical ratio = %.2f',emp_ratio), ...
     sprintf('Empirical 95%% CI = %.2f-%.2f',emp_ci(1),emp_ci(2)), ...
     sprintf('Reference prediction (R = %.2f)',pred_prior)}, ...
    'Location','northeast', ...
    'Box','on');

lgdA.Color = [0.94 0.94 0.94];

% ------------------- Subject strip adjacent to Panel A -------------------
% Subject ratios have no tau_max^scr coordinate, so they are displayed
% separately while sharing the y-axis range of Panel A.

axS = axes('Position',[0.392 0.130 0.048 0.760]);
hold(axS,'on');

set(axS, ...
    'FontSize',12, ...
    'LineWidth',1, ...
    'Box','on', ...
    'XTick',[], ...
    'YTick',[], ...
    'YAxisLocation','right');

fill(axS, ...
    [0 1 1 0], ...
    [emp_ci(1) emp_ci(1) emp_ci(2) emp_ci(2)], ...
    [0.84 0.87 0.94], ...
    'EdgeColor','none');

plot(axS, ...
    [0 1], ...
    [emp_ratio emp_ratio], ...
    '-', ...
    'Color',[0 0 0], ...
    'LineWidth',2.0);

x_jitter = 0.5 + 0.26*(2*rand(size(subj_ratios)) - 1);

plot(axS, ...
    x_jitter, ...
    subj_ratios, ...
    'o', ...
    'MarkerSize',5.5, ...
    'MarkerFaceColor',[0.45 0.45 0.45], ...
    'MarkerEdgeColor',[0.15 0.15 0.15], ...
    'LineWidth',0.6);

xlim(axS,[0 1]);
ylim(axS,[y_lo y_hi]);

xlabel(axS, ...
    sprintf('Subjects\n(n = %d)',numel(subj_ratios)), ...
    'FontSize',11);

% =========================== PANEL B =====================================
axB = axes('Position',[0.545 0.130 0.330 0.760]);

imagesc(axB, ...
    tau_scram_vals, ...
    alpha_vals, ...
    ratio_surface);

set(axB, ...
    'YDir','normal', ...
    'FontSize',12, ...
    'LineWidth',1);

xlim(axB,[tau_scram_vals(1) tau_scram_vals(end)]);

% IMPORTANT:
% Display the complete alpha range explicitly.
ylim(axB,[0 2]);
yticks(axB,[0 1 2]);
yticklabels(axB,{'0','1','2'});

hold(axB,'on');

% Empirical 95% CI boundaries
[~,h_low] = contour(axB, ...
    tau_scram_vals, ...
    alpha_vals, ...
    ratio_surface, ...
    [emp_ci(1) emp_ci(1)], ...
    'LineWidth',1.8, ...
    'LineStyle','--', ...
    'LineColor',[1 1 1]);

[~,h_high] = contour(axB, ...
    tau_scram_vals, ...
    alpha_vals, ...
    ratio_surface, ...
    [emp_ci(2) emp_ci(2)], ...
    'LineWidth',1.8, ...
    'LineStyle','--', ...
    'LineColor',[1 1 1]);

% Empirical point estimate
[~,h_mid] = contour(axB, ...
    tau_scram_vals, ...
    alpha_vals, ...
    ratio_surface, ...
    [emp_ratio emp_ratio], ...
    'LineWidth',2.4, ...
    'LineStyle','-', ...
    'LineColor',[0 0 0]);

% Reference parameter point at its true location:
% tau_max^scr = 7.5 s, alpha = 0.
%
% Clipping is disabled because alpha = 0 lies exactly on the lower
% boundary of Panel B.

plot(axB, ...
    tau_scram_prior, ...
    alpha_prior, ...
    'o', ...
    'MarkerSize',15, ...
    'MarkerFaceColor','w', ...
    'MarkerEdgeColor','w', ...
    'LineWidth',3, ...
    'Clipping','off', ...
    'HandleVisibility','off');

h_refB = plot(axB, ...
    tau_scram_prior, ...
    alpha_prior, ...
    'o', ...
    'MarkerSize',10, ...
    'MarkerFaceColor','w', ...
    'MarkerEdgeColor','k', ...
    'LineWidth',1.5, ...
    'Clipping','off');

xlabel(axB, ...
    'Maximum scrambled-condition timescale, \tau_{max}^{scr} (s)');

ylabel(axB, ...
    'Spectral exponent, \alpha');

title(axB, ...
    'B   Parameter space', ...
    'FontWeight','bold', ...
    'HorizontalAlignment','left', ...
    'Units','normalized', ...
    'Position',[0 1.02]);

% Colorbar
cb = colorbar(axB);
cb.Position = [0.892 0.130 0.017 0.760];
ylabel(cb,'Predicted variance ratio');

% Legend
lgdB = legend(axB, ...
    [h_mid h_low h_refB], ...
    {sprintf('Empirical ratio = %.2f',emp_ratio), ...
     sprintf('Empirical 95%% CI = %.2f-%.2f',emp_ci(1),emp_ci(2)), ...
     sprintf('Reference prediction (R = %.2f)',pred_prior)}, ...
    'Location','northeast', ...
    'Box','on');

lgdB.Color = [0.94 0.94 0.94];

sgtitle( ...
    'Model-predicted intact/scrambled variance ratio', ...
    'FontWeight','bold', ...
    'FontSize',14);

% -------------------------------------------------------------------------
% Save figure to repository figures/ directory
% -------------------------------------------------------------------------
script_dir = fileparts(mfilename('fullpath'));
repo_dir   = fileparts(script_dir);
figure_dir = fullfile(repo_dir, 'figures');
if ~exist(figure_dir,'dir'), mkdir(figure_dir); end

png_file = fullfile(figure_dir,'parameter_space_variance_ratio.png');
pdf_file = fullfile(figure_dir,'parameter_space_variance_ratio.pdf');
svg_file = fullfile(figure_dir,'parameter_space_variance_ratio.svg');

print(fig,png_file,'-dpng','-r300');
print(fig,pdf_file,'-dpdf','-painters');
print(fig,svg_file,'-dsvg','-painters');

fprintf('\nSaved figures to:\n%s\n%s\n%s\n', png_file, pdf_file, svg_file);


% =========================================================================
% HELPER FUNCTION
% =========================================================================
function G = compute_G( ...
    tau_min, ...
    tau_max, ...
    omega_min, ...
    omega_max, ...
    n_u, ...
    alpha)

    Delta = log(tau_max/tau_min);

    u_min = max(omega_min*tau_min,eps);
    u_max = max(omega_max*tau_min,eps);

    u_vec = logspace( ...
        log10(u_min), ...
        log10(u_max), ...
        n_u);

    log_term = 0.5*log( ...
        exp(2*Delta).*(1 + u_vec.^2) ./ ...
        (1 + u_vec.^2.*exp(2*Delta)));

    atan_term = ...
        atan(u_vec.*exp(Delta)) - atan(u_vec);

    g_u = ...
        (u_vec.^(-alpha)) .* ...
        (log_term.^2 + atan_term.^2);

    % Jacobian for integration in log(u)
    G = trapz(log(u_vec),g_u.*u_vec);
end